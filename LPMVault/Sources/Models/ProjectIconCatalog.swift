/// The symbols and emoji the icon picker offers, each with words it's found by.
enum ProjectIconCatalog {
	struct Entry: Sendable, Identifiable {
		let value: String
		let keywords: String
		/// What VoiceOver and the tooltip call it: a symbol's plain name, or an emoji's first word.
		let title: String

		init(value: String, keywords: String, title: String? = nil) {
			self.value = value
			self.keywords = keywords
			self.title = title ?? keywords.split(separator: " ").first.map { $0.prefix(1).uppercased() + $0.dropFirst() } ?? value
		}

		var id: String { value }

		func matches(_ query: String) -> Bool {
			value.localizedCaseInsensitiveContains(query) || title.localizedCaseInsensitiveContains(query)
				|| keywords.localizedCaseInsensitiveContains(query)
		}
	}

