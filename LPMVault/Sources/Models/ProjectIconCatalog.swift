	static func symbols(matching query: String) -> [Entry] { entries(symbols, matching: query) }

	static func emoji(matching query: String) -> [Entry] { entries(emoji, matching: query) }

	private static func entries(_ entries: [Entry], matching query: String) -> [Entry] {
		let query = query.trimmingCharacters(in: .whitespacesAndNewlines)
		guard !query.isEmpty else { return entries }
		return entries.filter { $0.matches(query) }
	}
